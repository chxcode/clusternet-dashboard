func registrationObject() *unstructured.Unstructured {
	return &unstructured.Unstructured{Object: map[string]any{"apiVersion": registrationGVR.GroupVersion().String(), "kind": "ClusterRegistrationRequest",
		"metadata": map[string]any{"name": "clusternet-" + demoID1, "uid": "old", "resourceVersion": "7"}, "spec": map[string]any{"clusterId": demoID1, "clusterNamespace": "tenant"}}}
}

func registrationFixture(objects ...runtime.Object) (*fake.FakeDynamicClient, *Explorer) {
	client := fake.NewSimpleDynamicClientWithCustomListKinds(runtime.NewScheme(), map[schema.GroupVersionResource]string{
		registrationGVR: "ClusterRegistrationRequestList", deploymentNamespaces: "NamespaceList", managedClusterGVR: "ManagedClusterList",
	}, objects...)
	return client, NewExplorer(nil, nil, client)
}

func TestRegistrationWithdrawalEligibility(t *testing.T) {
	for _, each := range []struct {
		name   string
		mode   string
		status map[string]any
	}{
		{"pending explicit namespace", "pendingNamespace", nil}, {"failed", "failed", map[string]any{"result": "Failed"}}, {"denied", "denied", map[string]any{"result": "Denied"}},
		{"approved", "", map[string]any{"result": "Approved"}}, {"unknown", "", map[string]any{"result": "SomethingElse"}}, {"empty value", "", map[string]any{"result": ""}},
		{"token", "", map[string]any{"result": "Failed", "token": "secret-marker"}}, {"CA", "", map[string]any{"result": "Denied", "caCertificate": "secret-marker"}},
		{"allocated namespace", "", map[string]any{"dedicatedNamespace": "allocated"}}, {"allocated mcls", "", map[string]any{"managedClusterName": "edge"}},
		{"unexpected credentials", "", map[string]any{"token": map[string]any{}}}, {"unknown result shape", "", map[string]any{"result": map[string]any{}}},
		{"pending autogenerated", "", nil}, {"terminating", "", nil},
	} {
		t.Run(each.name, func(t *testing.T) {
			r := registrationObject()
			if each.status != nil {
				r.Object["status"] = each.status
			}
			if each.name == "pending autogenerated" {
				unstructured.RemoveNestedField(r.Object, "spec", "clusterNamespace")
			}
			if each.name == "terminating" {
				ts := metav1.Now()
				r.SetDeletionTimestamp(&ts)
			}
			if got := registrationSummary(r).DeletionMode; got != each.mode {
				t.Fatalf("mode %q want %q", got, each.mode)
			}
			client, e := registrationFixture(r)
			err := e.DeleteFailedRegistration(t.Context(), r.GetName(), "old", "7", r.GetName())
			if each.mode != "" && err != nil || each.mode == "" && !apierrors.IsConflict(err) {
				t.Fatalf("unexpected deletion result %v", err)
			}
			writes := 0
			for _, a := range client.Actions() {
				if a.GetVerb() == "delete" {
					writes++
				}
			}
			if each.mode == "" && writes != 0 || each.mode != "" && writes != 1 {
				t.Fatalf("writes %d", writes)
			}
		})
	}
}

func TestRegistrationRejectsReplacedOrAllocatedIdentity(t *testing.T) {
	for _, s := range []string{"new UID", "new version", "allocated namespace", "allocated managedcluster", "denied name ID allocated", "check forbidden", "missing name confirmation"} {
		t.Run(s, func(t *testing.T) {
			r := registrationObject()
			objects := []runtime.Object{r}
			switch s {
			case "new UID":
				r.SetUID("replacement")
			case "new version":
				r.SetResourceVersion("8")
			case "allocated namespace":
				objects = append(objects, deployNamespace("allocated", demoID1))
			case "allocated managedcluster":
				objects = append(objects, deployCluster("allocated", demoID1))
			case "denied name ID allocated":
				r.Object["spec"].(map[string]any)["clusterId"] = demoID2
				r.Object["status"] = map[string]any{"result": "Denied"}
				objects = append(objects, deployNamespace("allocated", demoID1))
			}
			client, e := registrationFixture(objects...)
			name := r.GetName()
			if s == "check forbidden" {
				client.PrependReactor("list", "namespaces", func(clienttesting.Action) (bool, runtime.Object, error) {
					return true, nil, apierrors.NewForbidden(deploymentNamespaces.GroupResource(), "", errors.New("secret-marker"))
				})
			}
			confirm := name
			if s == "missing name confirmation" {
				confirm = ""
			}
			err := e.DeleteFailedRegistration(t.Context(), name, "old", "7", confirm)
			if err == nil || strings.Contains(err.Error(), "secret-marker") {
				t.Fatalf("unexpected %v", err)
			}
			for _, a := range client.Actions() {
				if a.GetVerb() == "delete" {
					t.Fatal("deleted a protected CRR")
				}
			}
		})
	}
}

func TestRegistrationNamespaceEvidenceAndSafeDetails(t *testing.T) {
	r := registrationObject()
	r.Object["status"] = map[string]any{"errorMessage": "namespaces tenant already exists, secret-marker", "result": "Failed"}
	foreign := deployNamespace("tenant", demoID2)
	client, e := registrationFixture(r, foreign)
	rows, err := e.Registrations(t.Context())
	if err != nil || len(rows) != 1 || rows[0].NamespaceEvidence != "occupied" || rows[0].FailureReason == "" {
		t.Fatalf("evidence %+v %v", rows, err)
	}
	raw, _ := json.Marshal(rows)
	if strings.Contains(string(raw), "secret-marker") {
		t.Fatal("error text leaked")
	}
	own := deployNamespace("different", demoID1)
	labels := own.GetLabels()
	labels["clusternet.io/created-by"] = "clusternet-agent"
	own.SetLabels(labels)
	if err = client.Tracker().Add(own); err != nil {
		t.Fatal(err)
	}
	rows, err = e.Registrations(t.Context())
	if err != nil || rows[0].NamespaceEvidence != "allocated" || rows[0].DeletionMode != "" {
		t.Fatalf("existing same-ID namespace must take precedence: %+v %v", rows, err)
	}
	client.PrependReactor("list", "namespaces", func(clienttesting.Action) (bool, runtime.Object, error) { return true, nil, errors.New("forbidden") })
	rows, err = e.Registrations(t.Context())
	if err != nil || len(rows) != 1 || rows[0].NamespaceEvidence != "" {
		t.Fatalf("optional namespace evidence blocked list %v %v", rows, err)
	}
}

func TestRegistrationWithdrawalWirePreconditionsAndRecovery(t *testing.T) {
	r := registrationObject()
	name := r.GetName()
	writes := 0
	ns := deployNamespace("tenant", demoID2)
	transport := restfake.CreateHTTPClient(func(req *http.Request) (*http.Response, error) {
		var obj any
		switch req.Method + " " + req.URL.Path {
		case "GET /apis/clusters.clusternet.io/v1beta1/clusterregistrationrequests/" + name:
			obj = r.Object
		case "GET /api/v1/namespaces":
			obj = map[string]any{"kind": "NamespaceList", "apiVersion": "v1", "items": []any{ns.Object}}
		case "GET /apis/clusters.clusternet.io/v1beta1/managedclusters":
			obj = map[string]any{"kind": "ManagedClusterList", "apiVersion": managedClusterGVR.GroupVersion().String(), "items": []any{}}
		case "DELETE /apis/clusters.clusternet.io/v1beta1/clusterregistrationrequests/" + name:
			var d metav1.DeleteOptions
			if err := json.NewDecoder(req.Body).Decode(&d); err != nil {
				return nil, err
			}
			if d.Preconditions == nil || d.Preconditions.UID == nil || *d.Preconditions.UID != "old" || d.Preconditions.ResourceVersion == nil || *d.Preconditions.ResourceVersion != "7" || d.PropagationPolicy == nil || *d.PropagationPolicy != metav1.DeletePropagationOrphan || d.GracePeriodSeconds != nil {
				return nil, fmt.Errorf("unexpected options %+v", d)
			}
			writes++
			obj = map[string]any{"kind": "Status", "apiVersion": "v1", "status": "Success"}
		default:
			return nil, fmt.Errorf("unexpected request %s %s", req.Method, req.URL.Path)
		}
		data, _ := json.Marshal(obj)
		return &http.Response{StatusCode: 200, Header: http.Header{"Content-Type": []string{"application/json"}}, Body: io.NopCloser(strings.NewReader(string(data)))}, nil
	})
	e, err := NewExplorerFromConfig(&rest.Config{Host: "https://fixture.invalid", Transport: transport.Transport})
	if err != nil {
		t.Fatal(err)
	}
	if err = e.DeleteFailedRegistration(t.Context(), name, "old", "7", name); err != nil {
		t.Fatal(err)
	}
	r.SetUID("new")
	r.SetResourceVersion("8")
	r.Object["status"] = map[string]any{"result": "Approved", "token": "secret-marker"}
	if err = e.DeleteFailedRegistration(t.Context(), name, "old", "7", name); !apierrors.IsConflict(err) || writes != 1 {
		t.Fatalf("old consent repeated: %v, writes %d", err, writes)
	}
}
